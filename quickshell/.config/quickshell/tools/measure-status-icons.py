"""Measure actual glyph outlines, including fallback fonts, for StatusIcon.qml.

Run with QT_QPA_PLATFORM=offscreen python tools/measure-status-icons.py.
Requires PyQt6. Regenerate after changing the icon font.
"""

import json
from pathlib import Path

from PyQt6.QtGui import QFont, QGuiApplication, QPainterPath, QTextLayout


app = QGuiApplication([])
family = "JetBrainsMono NF"
font = QFont(family)
font.setPixelSize(64)
font.setBold(True)
icons = {
    "Updates": "󰚰",
    "CPU": "",
    "Memory": "󰍛",
    "Disk": "",
    "Muted volume": "󰖁",
    "Low volume": "󰕿",
    "Medium volume": "󰖀",
    "High volume": "󰕾",
    "Muted microphone": "",
    "Microphone": "",
}
bounds = {}
for name, text in icons.items():
    layout = QTextLayout(text, font)
    layout.beginLayout()
    line = layout.createLine()
    layout.endLayout()
    outline = QPainterPath()
    for run in layout.glyphRuns():
        for glyph, position in zip(run.glyphIndexes(), run.positions()):
            path = run.rawFont().pathForGlyph(glyph)
            path.translate(position.x(), position.y() - line.ascent())
            outline.addPath(path)
    rect = outline.boundingRect()
    bounds[text] = [rect.x(), rect.y(), rect.width(), rect.height()]
    scale = 16 / max(rect.width(), rect.height())
    print(f"{name:18} visible bounds: {rect.width() * scale:5.2f} × {rect.height() * scale:5.2f}px")

output = Path(__file__).resolve().parents[1] / "components/StatusIconMetrics.js"
output.write_text(
    "// Generated by tools/measure-status-icons.py at 64px, bold.\n"
    ".pragma library\n\n"
    f"var fontFamily = {json.dumps(family)};\n"
    f"var bounds = {json.dumps(bounds, ensure_ascii=False, indent=4)};\n"
)
